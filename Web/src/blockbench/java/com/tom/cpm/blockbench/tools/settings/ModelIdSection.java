package com.tom.cpm.blockbench.tools.settings;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

import com.tom.cpm.blockbench.format.ProjectData;
import com.tom.cpm.blockbench.proxy.Dialog;
import com.tom.cpm.blockbench.proxy.Project;
import com.tom.cpm.blockbench.util.CommandArg;
import com.tom.cpm.blockbench.util.PlusDialogs;
import com.tom.cpm.blockbench.util.PlusDialogs.FormRow;
import com.tom.cpm.blockbench.util.ProjectDataUndo;

import jsinterop.base.JsPropertyMap;

/**
 * CPM+ (W5-CMDS, G11): 'ID do modelo' section of 'Ajustes do modelo'. The model ID lets the game remember each
 * player's choices ('Salvar entre partidas') and keybinds for THIS model (CPM: modelProfilesId = editor.modelId).
 * <ul>
 * <li>[Gerar]: slug of the project name (a-z 0-9 -, up to 24) + '-' + 6 base36 characters from
 * crypto.getRandomValues; only while the field is empty (changing an existing ID makes players lose their choices,
 * so the user clears it by hand and confirms);</li>
 * <li>[Copiar]; empty = no ID (never ''); never regenerated by itself (import, reload, 'save as' keep it);</li>
 * <li>a change is not in Blockbench's Ctrl+Z (project data): the toast 'Desfazer' restores the previous ID, also
 * 'none'.</li>
 * </ul>
 */
public final class ModelIdSection {
	public static final String DIALOG_ID = "cpmplus_w5cmds_modelid";
	public static final String ID_REGEX = "^[a-z0-9-]{1,24}-[0-9a-z]{6}$";

	private ModelIdSection() {
	}

	public static void install() {
		ModelSettings.addSection("modelId", "cpmplus.w5cmds.modelId.section", 30, ModelIdSection::open);
	}

	/** the model ID of the open project (null = none) */
	public static String current() {
		String v = Project.getData().modelId;
		// a ProjectData re-read after 'Desfazer' leaves the field undefined in JS: always a real null for 'no ID'
		return v == null || v.trim().isEmpty() ? null : v;
	}

	/** project name -> 'a-z0-9-' slug, up to 24 characters, 'modelo' when empty */
	public static String slug(String name) {
		String s = CommandArg.safeNameSuggestion(name == null ? "" : name);
		if ("nome".equals(s) && (name == null || !name.toLowerCase(Locale.ROOT).contains("nome")))s = "";
		s = s.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9]+", "-").replaceAll("-+", "-");
		s = s.replaceAll("^-+", "").replaceAll("-+$", "");
		if (s.length() > 24)s = s.substring(0, 24).replaceAll("-+$", "");
		return s.isEmpty() ? "modelo" : s;
	}

	/** a new ID: slug + '-' + 6 random base36 characters (crypto.getRandomValues) */
	public static String generate(String projectName) {
		String r = random36();
		if (r == null || r.length() != 6)r = Long.toString(System.currentTimeMillis() % 2176782336L + 2176782336L, 36).substring(1, 7);
		return slug(projectName) + "-" + r;
	}

	/** 6 base36 characters from crypto.getRandomValues */
	private static native String random36() /*-{
		var digits = '0123456789abcdefghijklmnopqrstuvwxyz';
		var a = new Uint32Array(6);
		var c = $wnd.crypto || $wnd.msCrypto;
		if (c && c.getRandomValues) c.getRandomValues(a);
		else for (var i = 0; i < 6; i++) a[i] = Math.floor(Math.random() * 4294967296);
		var s = '';
		for (var j = 0; j < 6; j++) s += digits.charAt(a[j] % 36);
		return s;
	}-*/;

	/** sets the ID (trimmed; empty = none) with the 'Desfazer' toast; true when it changed */
	public static boolean set(String id) {
		String v = id == null ? null : id.trim();
		if (v != null && v.isEmpty())v = null;
		ProjectData pd = Project.getData();
		String old = pd.modelId;
		if (old == null ? v == null : old.equals(v))return false;
		ProjectDataUndo.Snapshot s = ProjectDataUndo.snapshot();
		pd = Project.getData();
		pd.modelId = v;
		pd.flush();
		Project.saved = false;
		ProjectDataUndo.offerUndo(s, v == null ? PlusDialogs.tr("cpmplus.w5cmds.modelId.cleared") : PlusDialogs.trf("cpmplus.w5cmds.modelId.changed", v));
		return true;
	}

	/** creates an ID now when there is none (wizard '[Criar ID autom\u00e1tico]', export fix); returns the ID */
	public static String createIfMissing() {
		String cur = current();
		if (cur != null && !cur.trim().isEmpty())return cur;
		String id = generate(Project.name);
		set(id);
		return id;
	}

	/** the section dialog */
	public static void open() {
		String cur = current();
		List<FormRow> rows = new ArrayList<>();
		rows.add(FormRow.info("about", null, "cpmplus.w5cmds.modelId.about"));
		rows.add(FormRow.text("id", "cpmplus.w5cmds.modelId.field", cur != null ? cur : "").placeholder("cpmplus.w5cmds.modelId.placeholder"));
		Dialog[] dlg = new Dialog[1];
		rows.add(FormRow.buttons("actions", null, new String[] {"cpmplus.w5cmds.modelId.generate", "cpmplus.w5cmds.modelId.copy"}, i -> {
			PlusDialogs.FormResult fr = new PlusDialogs.FormResult(dlg[0] != null ? dlg[0].getFormResult() : null);
			String v = fr.getString("id");
			v = v == null ? "" : v.trim();
			if (i == 0) {
				if (!v.isEmpty()) {
					PlusDialogs.quick(PlusDialogs.tr("cpmplus.w5cmds.modelId.generateBlocked"), 5000);
					return;
				}
				JsPropertyMap<Object> vals = JsPropertyMap.of();
				vals.set("id", generate(Project.name));
				dlg[0].setFormValues(vals, true);
			} else {
				if (v.isEmpty())PlusDialogs.quick(PlusDialogs.tr("cpmplus.w5cmds.modelId.nothingToCopy"), 3000);
				else PlusDialogs.copyText(v);
			}
		}));
		rows.add(FormRow.info("warn", null, "cpmplus.w5cmds.modelId.warn"));
		dlg[0] = PlusDialogs.form(DIALOG_ID, "cpmplus.w5cmds.modelId.title", rows, res -> {
			String v = res.getString("id");
			v = v == null ? "" : v.trim();
			String old = current();
			if (old != null && !old.equals(v)) {
				String nv = v;
				PlusDialogs.confirm("cpmplus_w5cmds_modelid_change", "cpmplus.w5cmds.modelId.title", "cpmplus.w5cmds.modelId.confirmChange", () -> set(nv), null);
				return;
			}
			set(v);
		});
	}
}
